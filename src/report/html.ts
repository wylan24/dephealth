const JS = `
(() => {
const R = JSON.parse(document.getElementById('data').textContent);
const $ = (s) => document.querySelector(s);
const el = (tag, props = {}, ...kids) => { const e = document.createElement(tag); for (const [k, v] of Object.entries(props)) { if (k === 'class') e.className = v; else if (k === 'text') e.textContent = v; else e.setAttribute(k, v); } for (const k of kids) if (k != null) e.append(k); return e; };
const CATS = ['insecure', 'abandoned', 'outdated', 'weight'];
const LABEL = { insecure: 'Insecure', abandoned: 'Abandoned', outdated: 'Outdated', weight: 'Heavy' };
const scoreCol = (n) => n >= 80 ? 'var(--ok)' : n >= 50 ? 'var(--med)' : 'var(--crit)';
const ignored = (p, f) => p.ignored && (p.ignored.checks === 'all' || p.ignored.checks.includes(f.category));
const active = (p) => p.findings.filter((f) => !ignored(p, f));

$('#title').textContent = R.workspaces[0]?.name ?? R.root;
$('#meta').textContent = new Date(R.generatedAt).toLocaleString() + ' · ' + R.lockfile.kind + ' lockfile · ' + R.workspaces.length + ' workspace' + (R.workspaces.length > 1 ? 's' : '') + ' · dephealth ' + R.tool.version;

const s = R.summary, v = s.vulnerabilities;
const card = (val, label, sub, color) => { const c = el('div', { class: 'card' }, el('div', { class: 'v', text: String(val) }), el('div', { class: 'l', text: label }), sub ? el('div', { class: 's', text: sub }) : null); if (color) c.firstChild.style.color = color; return c; };
$('#cards').append(
  card(s.averageScore, 'Average score', 'direct dependencies', scoreCol(s.averageScore)),
  card(s.byCategory.insecure, 'Insecure', v.critical + ' critical · ' + v.high + ' high · ' + v.moderate + ' moderate', s.byCategory.insecure ? 'var(--crit)' : null),
  card(s.byCategory.abandoned, 'Abandoned / at risk'),
  card(s.byCategory.outdated, 'Outdated', s.totalLibyear + ' libyears behind'),
  card(s.byCategory.weight, 'Heavier than needed'),
  card(s.packages, 'Packages', s.direct + ' direct · ' + (s.packages - s.assessed) + ' not assessed'),
);
for (const w of R.warnings) $('#warnings').append(el('div', { class: 'warn', text: w }));

const acts = R.actions.slice(0, 10);
if (!acts.length) $('#actions').append(el('li', {}, el('div', { class: 't', text: 'Nothing to do — every dependency looks healthy.' })));
for (const a of acts) $('#actions').append(el('li', {}, el('div', { class: 't' }, el('span', { class: 'tag', text: LABEL[a.category] }), a.package + ' — ' + a.title), el('div', { class: 'd', text: a.detail })));

const state = { q: '', cats: new Set(), directOnly: true, problemsOnly: true, hideDev: false, sort: 'score', dir: 1, open: new Set() };
for (const c of CATS) {
  const b = el('button', { class: 'chip', type: 'button', 'aria-pressed': 'false', text: LABEL[c] });
  b.onclick = () => { state.cats.has(c) ? state.cats.delete(c) : state.cats.add(c); b.setAttribute('aria-pressed', String(state.cats.has(c))); draw(); };
  $('#chips').append(b);
}
$('#q').oninput = (e) => { state.q = e.target.value.toLowerCase(); draw(); };
for (const id of ['directOnly', 'problemsOnly', 'hideDev']) $('#' + id).onchange = (e) => { state[id] = e.target.checked; draw(); };
document.querySelectorAll('th[data-k]').forEach((th) => th.onclick = () => { const k = th.dataset.k; state.dir = state.sort === k ? -state.dir : 1; state.sort = k; draw(); });

const key = {
  name: (p) => p.name, version: (p) => p.semverBehind === 'major' ? 0 : p.semverBehind === 'minor' ? 1 : p.semverBehind === 'patch' ? 2 : 3,
  score: (p) => p.assessed ? p.score : 101, issues: (p) => -active(p).length, libyear: (p) => -(p.libyear ?? 0), vulns: (p) => -p.vulnerabilities.length,
  kind: (p) => (p.direct ? 0 : 2) + (p.dev ? 1 : 0),
};

function detail(p) {
  const box = el('div');
  const list = (title, items) => { if (!items.length) return; box.append(el('h4', { text: title })); const ul = el('ul'); items.forEach((i) => ul.append(i)); box.append(ul); };
  if (!p.assessed) box.append(el('p', { text: 'Not assessed: ' + (p.notAssessedReason ?? 'private package') }));
  if (p.ignored) box.append(el('p', { text: 'Ignored (' + (p.ignored.checks === 'all' ? 'all checks' : p.ignored.checks.join(', ')) + '): ' + p.ignored.reason }));
  list('Why this score (' + p.score + '/100)', p.findings.map((f) => el('li', {}, el('span', { class: 'tag ' + f.level, text: f.level }), f.message + (f.penalty ? ' (−' + f.penalty + ')' : '') + (ignored(p, f) ? ' [ignored]' : ''), f.fix ? el('div', { class: 'fix', text: '→ ' + f.fix }) : null)));
  list('Replacement suggestions', p.replacements.map((r) => el('li', {}, r.url ? el('a', { href: r.url, target: '_blank', rel: 'noopener noreferrer', text: r.name }) : el('strong', { text: r.name }), el('span', { class: 'effort', text: r.effort }), el('span', { class: 'effort', text: r.source === 'search' ? 'candidate, not a recommendation' : r.source === 'author' ? 'from the author' : 'curated' }), r.note ? ' — ' + r.note : '')));
  if (p.abandonment) list('Maintenance signals', [...p.abandonment.failed.map((t) => el('li', { text: '✗ ' + t })), ...p.abandonment.passed.map((t) => el('li', { text: '✓ ' + t }))]);
  const facts = [];
  if (p.via.length) facts.push('Pulled in by: ' + p.via.join(', '));
  if (p.workspaces.length) facts.push('Workspaces: ' + p.workspaces.join(', ') + ' (' + p.depTypes.join(', ') + ')');
  if (p.registry?.lastPublish) facts.push('Last publish: ' + p.registry.lastPublish.slice(0, 10));
  if (p.registry?.weeklyDownloads != null) facts.push('Weekly downloads: ' + p.registry.weeklyDownloads.toLocaleString());
  if (p.repo?.scorecard != null) facts.push('OpenSSF Scorecard: ' + p.repo.scorecard + '/10');
  if (p.weight) facts.push('Transitive packages: ' + p.weight.transitiveCount + (p.weight.unpackedSize ? ' · unpacked ' + Math.round(p.weight.unpackedSize / 1024) + ' kB' : '') + (p.weight.bundle ? ' · bundle ' + Math.round(p.weight.bundle.gzip / 1024) + ' kB gzip' : ''));
  list('Facts', facts.map((t) => el('li', { text: t })));
  list('Advisories', p.vulnerabilities.map((x) => el('li', {}, el('a', { href: x.url, target: '_blank', rel: 'noopener noreferrer', text: x.id }), ' ' + x.severity + (x.fixedIn ? ', fixed in ' + x.fixedIn : ', no fix yet'))));
  return box;
}

function draw() {
  const rows = R.packages.filter((p) =>
    (!state.directOnly || p.direct) && (!state.hideDev || !p.dev) && (!state.q || p.name.toLowerCase().includes(state.q)) &&
    (!state.problemsOnly || active(p).some((f) => f.level !== 'info') || !p.assessed) &&
    (!state.cats.size || active(p).some((f) => state.cats.has(f.category))));
  const k = key[state.sort];
  rows.sort((a, b) => { const x = k(a), y = k(b); return (x < y ? -1 : x > y ? 1 : a.name.localeCompare(b.name)) * state.dir; });
  document.querySelectorAll('th[data-k]').forEach((th) => th.dataset.k === state.sort ? th.setAttribute('aria-sort', state.dir > 0 ? 'ascending' : 'descending') : th.removeAttribute('aria-sort'));
  const tb = $('#table tbody'); tb.replaceChildren();
  for (const p of rows) {
    const cats = [...new Set(active(p).filter((f) => f.level !== 'info').map((f) => f.category))];
    const worst = (c) => { const order = ['critical', 'high', 'medium', 'low', 'info']; return active(p).filter((f) => f.category === c).map((f) => f.level).sort((a, b) => order.indexOf(a) - order.indexOf(b))[0]; };
    const bar = el('span', { class: 'bar' }, el('i')); bar.firstChild.style.width = p.score + '%'; bar.firstChild.style.background = scoreCol(p.score);
    const tr = el('tr', { class: 'row', tabindex: '0', 'aria-expanded': String(state.open.has(p.id)) },
      el('td', { class: 'name', text: p.name }),
      el('td', { class: 'ver', text: p.version + (p.latest && p.latest !== p.version ? ' → ' + p.latest : '') }),
      el('td', { class: 'num' }, p.assessed ? el('span', { class: 'score' }, bar, el('span', { text: String(p.score) })) : el('span', { class: 'meta', text: 'n/a' })),
      el('td', {}, ...cats.map((c) => el('span', { class: 'tag ' + worst(c), text: LABEL[c] })), p.ignored ? el('span', { class: 'tag', text: 'ignored' }) : null),
      el('td', { class: 'num', text: p.libyear != null ? String(p.libyear) : '' }),
      el('td', { class: 'num', text: p.vulnerabilities.length ? String(p.vulnerabilities.length) : '' }),
      el('td', { class: 'meta', text: (p.direct ? 'direct' : 'transitive') + (p.dev ? ', dev' : '') }));
    const toggle = () => { state.open.has(p.id) ? state.open.delete(p.id) : state.open.add(p.id); draw(); };
    tr.onclick = toggle; tr.onkeydown = (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); toggle(); } };
    tb.append(tr);
    if (state.open.has(p.id)) { const td = el('td', { colspan: '7' }, detail(p)); tb.append(el('tr', { class: 'detail' }, td)); }
  }
  $('#count').textContent = rows.length + ' of ' + R.packages.length + ' packages shown';
}
draw();

if (s.duplicates.length) {
  const d = el('details', {}, el('summary', { text: s.duplicates.length + ' packages locked at more than one version' }));
  const box = el('div', { class: 'dupes' });
  for (const x of s.duplicates) box.append(el('div', { text: x.name + ' ' + x.versions.join(', ') }));
  d.append(box); $('#dupes').append(d);
}
})();
`;
