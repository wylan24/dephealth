import type { Report } from '../types.ts';

/**
 * Self-contained interactive report: summary, top actions, and a sortable, filterable table.
 * All registry-sourced text (deprecation messages, advisories) is untrusted, so the page builds
 * the DOM with textContent only and the JSON payload is escaped against `</script>` breakout.
 */
export function renderHtml(report: Report): string {
  const data = JSON.stringify(report).replace(/</g, '\\u003c');
  const title = `dephealth — ${report.workspaces[0]?.name ?? 'report'}`.replace(/[<>&"]/g, '');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>${CSS}</style>
</head>
<body>
<header class="wrap">
  <div class="eyebrow">Dependency health report</div>
  <h1 id="title"></h1>
  <p class="meta" id="meta"></p>
</header>
<main class="wrap">
  <section class="cards" id="cards"></section>
  <section id="warnings"></section>
  <section>
    <h2>Top actions</h2>
    <ol class="actions" id="actions"></ol>
  </section>
  <section>
    <div class="table-head">
      <h2>Packages</h2>
      <div class="filters">
        <input id="q" type="search" placeholder="Filter by name…" aria-label="Filter by package name">
        <div class="chips" id="chips" role="group" aria-label="Category filter"></div>
        <label><input type="checkbox" id="directOnly" checked> Direct only</label>
        <label><input type="checkbox" id="problemsOnly" checked> Problems only</label>
        <label><input type="checkbox" id="hideDev"> Hide dev</label>
      </div>
    </div>
    <div class="table-scroll">
      <table id="table">
        <thead><tr>
          <th data-k="name">Package</th>
          <th data-k="version">Installed → latest</th>
          <th data-k="score" class="num">Score</th>
          <th data-k="issues">Issues</th>
          <th data-k="libyear" class="num">Libyear</th>
          <th data-k="vulns" class="num">Vulns</th>
          <th data-k="kind">Type</th>
        </tr></thead>
        <tbody></tbody>
      </table>
    </div>
    <p class="meta" id="count"></p>
  </section>
  <section id="dupes"></section>
</main>
<footer class="wrap meta">Generated by dephealth. Scores start at 100 and lose points for each finding; expand a row to see exactly why.</footer>
<script type="application/json" id="data">${data}</script>
<script>${JS}</script>
</body>
</html>
`;
}

